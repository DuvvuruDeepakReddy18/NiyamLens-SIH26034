import assert from 'node:assert/strict'
import { resolve } from 'node:path'
import { launchTestBrowser } from './browser-runtime.mjs'
const browser = await launchTestBrowser()
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto(process.env.NIYAMLENS_BASE_URL || 'http://127.0.0.1:4191/', { waitUntil: 'networkidle' })
  assert.equal(await page.locator('.field-review-row').count(), 0)
  assert.ok(await page.evaluate(() => document.documentElement.scrollHeight) < 1800, 'Empty inspection should be a short capture-first page.')
  await page.locator('input[type=file]').setInputFiles(resolve('public/sample-real-label.png'))
  await page.getByText(/panel ready for OCR/i).waitFor()
  const caution = page.getByRole('button', { name: 'Continue with caution', exact: true })
  if (await caution.count()) await caution.click()
  const digest = await page.locator('.hash-readout').innerText()
  assert.equal(await page.getByRole('button', { name: 'Deep scan small text', exact: true }).isVisible(), false)
  await page.getByText('More OCR options', { exact: true }).click()
  assert.equal(await page.getByRole('button', { name: 'Deep scan small text', exact: true }).isVisible(), true)
  await page.getByRole('button', { name: 'Run browser OCR', exact: true }).click()
  await page.getByText(/OCR complete across/i).waitFor({ timeout: 120000 })
  const raw = await page.locator('.evidence-editor').inputValue()
  assert.match(raw, /48.00/)
  await page.getByRole('button', { name: 'Select MRP region', exact: true }).click()
  await page.getByText('Select opposite corners around the complete declaration, including its heading', { exact: true }).waitFor()
  const layer = page.locator('.image-layer')
  const box = await layer.boundingBox()
  await layer.click({ position: { x: box.width * .05, y: box.height * .05 } })
  await layer.click({ position: { x: box.width * .95, y: box.height * .95 } })
  await page.getByRole('region', { name: 'Focused OCR rescan' }).waitFor()
  assert.equal(await page.locator('.hash-readout').innerText(), digest)
  await page.getByRole('textbox', { name: 'Maximum Retail Price verification note', exact: true }).fill('Synthetic test only: inspected MRP heading and amount together.')
  await page.locator('#verify-mrp').selectOption('confirmed')
  assert.equal(await page.locator('#verify-mrp').count(), 0, 'Verified field should leave the attention list without losing its stored review.')
  await page.locator('.evidence-editor').fill(raw.replaceAll('48.00', '49.00'))
  assert.equal(await page.locator('#verify-mrp').inputValue(), 'unreviewed', 'Changed value must reappear for review.')
  assert.equal(await page.locator('.transcript-original').textContent(), raw)
  await page.screenshot({ path: resolve('qa-capture-coach.png'), fullPage: true })
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ fixture: 'Generated package only, no real-label accuracy claim', captureFirst: true, advancedOptionsDisclosed: true, criticalFieldFocusSelection: true, originalHashPreserved: true, verifiedFieldCollapsed: true, changedValueReappears: true, rawTranscriptUnchanged: true, errors }, null, 2))
} finally { await browser.close() }
