import assert from 'node:assert/strict'
import path from 'node:path'
import { launchTestBrowser } from './browser-runtime.mjs'
const browser = await launchTestBrowser()
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } })
const errors = []
page.on('pageerror', (error) => errors.push(error.message))
try {
  await page.goto(process.env.NIYAMLENS_BASE_URL || 'http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
  await page.locator('input[type=file]').setInputFiles(path.join(process.cwd(), 'public/sample-real-label.svg'))
  await page.getByText(/panel ready for OCR/i).waitFor()
  await page.getByRole('button', { name: 'Run browser OCR', exact: true }).click()
  await page.getByText(/OCR complete across/i).waitFor({ timeout: 120000 })
  const raw = await page.locator('.evidence-editor').inputValue()
  assert.match(raw, /48.00/)
  await page.locator('#verify-mrp').selectOption('confirmed')
  await page.getByRole('textbox', { name: 'Maximum Retail Price verification note', exact: true }).fill('Synthetic test fixture: price visible on front panel.')
  assert.match(await page.locator('.checks-list .check-row').filter({ hasText: 'Maximum Retail Price' }).innerText(), /PASS/)
  await page.locator('.evidence-editor').fill(raw.replaceAll('48.00', '49.00'))
  assert.match(await page.locator('.checks-list .check-row').filter({ hasText: 'Maximum Retail Price' }).innerText(), /REVIEW/)
  assert.equal(await page.locator('.transcript-original').textContent(), raw)
  await page.waitForTimeout(600)
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByRole('button', { name: 'Restore draft' }).click()
  assert.match(await page.locator('.evidence-editor').inputValue(), /49.00/)
  assert.equal(await page.locator('.transcript-original').textContent(), raw)
  await page.getByRole('button', { name: 'Finalize inspection', exact: true }).click()
  await page.getByRole('button', { name: 'Start new inspection', exact: true }).waitFor()
  assert.equal(await page.locator('.evidence-editor').isDisabled(), true)
  await page.getByRole('button', { name: 'Open sealed report', exact: true }).click()
  await page.getByRole('heading', { name: 'Original OCR transcript before manual corrections' }).waitFor()
  assert.match(await page.locator('.report-text').filter({ hasText: 'Original OCR transcript before manual corrections' }).innerText(), /48.00/)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: 'Officer operations', exact: true }).click()
  await page.locator('.actor-switch select').selectOption('supervisor-01')
  for (const status of ['compliant', 'non_compliant']) {
    await page.getByRole('button', { name: 'Review / override', exact: true }).first().click()
    await page.locator('.override-modal select').selectOption(status)
    await page.getByPlaceholder(/State the physical evidence/i).fill(`Regression ${status}: reviewed synthetic fixture, not a real statutory approval.`)
    await page.getByRole('button', { name: 'Seal supervisor disposition', exact: true }).click()
    await page.locator('.override-modal').waitFor({ state: 'detached' })
  }
  await page.locator('.review-record').first().getByRole('button', { name: 'Evidence', exact: true }).click()
  const reviews = page.locator('.report-text').filter({ has: page.getByRole('heading', { name: 'Complete disposition history' }) })
  assert.equal(await reviews.locator('p').count(), 2)
  assert.match(await page.locator('.report-title .status-pill').innerText(), /MANUAL REVIEW/)
  assert.match(await page.locator('.report-supervisor .status-pill').innerText(), /FLAG/)
  await page.getByRole('button', { name: 'Close', exact: true }).click()
  await page.getByRole('button', { name: /Inspection history/ }).click()
  await page.getByRole('textbox', { name: 'Search inspections' }).fill('no-such-case-qa')
  await page.getByText('No matching inspections', { exact: true }).waitFor()
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ fixture: 'synthetic regression label; no field accuracy claim', realBrowserOcr: true, originalTranscriptPreserved: true, changedFieldRequiresReverification: true, draftRestoredAfterReload: true, sealedEvidenceLocked: true, twoReviewsPreserved: true, automatedFindingUnchanged: true, searchWorks: true, errors }, null, 2))
} finally { await browser.close() }
